export const companies: Company[] = rawCompanies.map((c) => {
  const distancesByOrigin: Record<string, number> = {};
  for (const o of DEFAULT_ORIGINS) {
    distancesByOrigin[o.id] = Math.round(haversine(c.lat, c.lng, o.lat, o.lng));
  }
  return { ...c, distancesByOrigin };
});

export function getCompaniesByState(): Record<string, Company[]> {
  const grouped: Record<string, Company[]> = {};
  for (const c of companies) {
    if (!grouped[c.state]) grouped[c.state] = [];
    grouped[c.state].push(c);
  }
  return grouped;
}

export function getUniqueGroups(): string[] {
  return [...new Set(companies.map((c) => c.group))];
}

export function getUniqueStates(): string[] {
  return [...new Set(companies.map((c) => c.state))].sort();
}

export function sortByDistance(list: Company[], originId: string): Company[] {
  return [...list].sort((a, b) => {
    const da = a.distancesByOrigin?.[originId];
    const db = b.distancesByOrigin?.[originId];
    if (da == null && db == null) return 0;
    if (da == null) return 1;
    if (db == null) return -1;
    return da - db;
  });
}
